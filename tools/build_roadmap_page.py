"""Build the one-page roadmap from the repository's sources of truth.

Usage: python tools/build_roadmap_page.py           # writes founder/roadmap.md
       python tools/build_roadmap_page.py --check   # exit 1 if founder/roadmap.md is out of date
       python tools/build_roadmap_page.py --html OUT  # also writes a standalone HTML page (phone view)

Reads: specs/001-detent-mvp/slices.yaml (order, names, status, goals, exits),
       backlog/stories.yaml (acceptance criteria and which are done),
       specs/001-detent-mvp/decisions.md (C- and G- items not yet Confirmed),
       founder/status.md (open founder items and what they block), if present.

Nothing here is hand-edited: change the sources, then run `make roadmap`. The output carries no
generation date so the CI check only fails when a source changed.
"""

from __future__ import annotations

import argparse
import html
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
FEAT = ROOT / "specs" / "001-detent-mvp"
OUT = ROOT / "founder" / "roadmap.md"
SLICE_REF = re.compile(r"\b(S\d+|P\d+|L)\b")


@dataclass
class Slice:
    id: str
    name: str
    status: str  # done | next | todo
    goal: str
    exit: str
    stories: list[str]
    done: int = 0
    total: int = 0
    open_stories: list[tuple[str, str, int, int]] = field(default_factory=list)
    blockers: list[str] = field(default_factory=list)


def _clean(text: str) -> str:
    return " ".join(str(text).split())


def load_slices() -> list[Slice]:
    raw = yaml.safe_load((FEAT / "slices.yaml").read_text())["slices"]
    stories = {s["id"]: s for s in yaml.safe_load((ROOT / "backlog" / "stories.yaml").read_text())["stories"]}
    out: list[Slice] = []
    seen_next = False
    for s in raw:
        status = "done" if s.get("status") == "done" else ("todo" if seen_next else "next")
        seen_next = seen_next or status == "next"
        sl = Slice(
            id=s["id"],
            name=re.sub(r"\s*\(done\)\s*$", "", s["name"]),
            status=status,
            goal=_clean(s.get("goal", "")),
            exit=_clean(s.get("exit", "")),
            stories=list(s["stories"]),
        )
        for sid in sl.stories:
            st = stories[sid]
            n_ac, n_done = len(st["ac"]), len(st.get("done", []))
            sl.total += n_ac
            sl.done += n_done
            if n_done < n_ac:
                sl.open_stories.append((sid, st["title"], n_done, n_ac))
        out.append(sl)
    return out


def _table_rows(text: str, header_start: str) -> list[list[str]]:
    """Rows of the first Markdown table whose header line starts with header_start."""
    lines = text.splitlines()
    rows: list[list[str]] = []
    for i, line in enumerate(lines):
        if line.startswith(header_start):
            for row in lines[i + 2 :]:
                if not row.startswith("|"):
                    break
                rows.append([c.strip() for c in row.strip().strip("|").split("|")])
            break
    return rows


def load_open_decisions() -> list[tuple[str, str, str]]:
    text = (FEAT / "decisions.md").read_text()
    out: list[tuple[str, str, str]] = []
    for header in ("| ID | Conflict", "| ID | Gap"):
        for cells in _table_rows(text, header):
            status = re.sub(r"\*", "", cells[-1]).split()[0] if cells[-1] else ""
            if status in ("Proposed", "Open"):
                out.append((cells[0], _clean(cells[1]), status))
    return out


def load_founder_items() -> list[tuple[str, str, str]] | None:
    path = ROOT / "founder" / "status.md"
    if not path.exists():
        return None
    return [(c[0], c[1], c[2]) for c in _table_rows(path.read_text(), "| Item | Owner") if len(c) >= 3]


def _bar(done: int, total: int, width: int = 10) -> str:
    filled = round(width * done / total) if total else 0
    return "█" * filled + "░" * (width - filled)


def _pct(done: int, total: int) -> str:
    return f"{round(100 * done / total)}%" if total else "–"


def build() -> tuple[str, dict[str, Any]]:
    slices = load_slices()
    decisions = load_open_decisions()
    items = load_founder_items()
    by_id = {s.id: s for s in slices}
    for item, _owner, needed in items or []:
        for ref in SLICE_REF.findall(needed):
            if ref in by_id:
                by_id[ref].blockers.append(item)

    done_c = sum(s.done for s in slices)
    total_c = sum(s.total for s in slices)
    n_done = sum(s.status == "done" for s in slices)
    nxt = next((s for s in slices if s.status == "next"), None)
    label = {"done": "Done", "next": "**Next**", "todo": "To do"}

    md: list[str] = [
        "# Roadmap",
        "",
        "Generated by `tools/build_roadmap.py` from `specs/001-detent-mvp/slices.yaml`, `backlog/stories.yaml`,",
        "`specs/001-detent-mvp/decisions.md` and `founder/status.md`. Do not edit by hand: change a source and run",
        "`make roadmap`. CI fails if this page is out of date.",
        "",
        f"**{n_done} of {len(slices)} slices done. {done_c} of {total_c} acceptance criteria done "
        f"({_pct(done_c, total_c)}).**" + (f" Next: **{nxt.id} {nxt.name}**." if nxt else ""),
        "",
        "## Slices",
        "",
        "| Slice | Status | Criteria | Progress | Goal |",
        "|---|---|---|---|---|",
    ]
    for s in slices:
        md.append(
            f"| {s.id} {s.name} | {label[s.status]} | {s.done}/{s.total} | `{_bar(s.done, s.total)}` "
            f"{_pct(s.done, s.total)} | {s.goal} |"
        )

    if nxt:
        md += ["", f"## Next: {nxt.id} {nxt.name}", "", f"**Exit check:** {nxt.exit}", ""]
        if nxt.blockers:
            md += ["**Blocked on the founder:**", ""] + [f"- {b}" for b in nxt.blockers] + [""]
        md += ["| Story | Title | Criteria |", "|---|---|---|"]
        md += [f"| {sid} | {title} | {d}/{t} |" for sid, title, d, t in nxt.open_stories]

    later = [s for s in slices if s.status == "todo" and s.blockers]
    if later:
        md += ["", "## Founder items for later slices", ""]
        for s in later:
            md.append(f"- **{s.id} {s.name}:** " + "; ".join(s.blockers))
    if items is None:
        md += ["", "_Founder items appear here once `founder/status.md` exists._"]

    md += ["", "## Decisions waiting on the founder", ""]
    if decisions:
        md += ["| ID | Item | Status |", "|---|---|---|"]
        md += [f"| {i} | {t[:140] + ('…' if len(t) > 140 else '')} | {st} |" for i, t, st in decisions]
    else:
        md.append("None. Every C- and G- item is Confirmed.")
    md.append("")

    data = {
        "slices": slices,
        "decisions": decisions,
        "done_c": done_c,
        "total_c": total_c,
        "n_done": n_done,
        "next": nxt,
        "later": later,
    }
    return "\n".join(md), data


