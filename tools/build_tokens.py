"""Build the console's CSS tokens from design/tokens.json, the one source of design tokens (DESIGN.md, D-39).

    python tools/build_tokens.py           # write apps/api/src/detent/console/static/tokens.css
    python tools/build_tokens.py --check   # fail if the file is out of date

The site reads the same JSON directly (apps/site/src/styles/palettes.mjs).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "design" / "tokens.json"
TARGET = ROOT / "apps" / "api" / "src" / "detent" / "console" / "static" / "tokens.css"


def kebab(name: str) -> str:
    return re.sub(r"[A-Z]", lambda m: "-" + m.group(0).lower(), name)


def render(tokens: dict) -> str:
    lines = [
        "/* Generated by tools/build_tokens.py from design/tokens.json. Do not edit; edit the JSON and rebuild. */",
        ":root {",
        "  color-scheme: light;",
    ]
    for key, value in tokens["console"].items():
        lines.append(f"  --{kebab(key)}: {value};")
    for key, value in tokens["font"].items():
        lines.append(f"  --font-{kebab(key)}: {value};")
    for key, value in tokens["size"]["console"].items():
        lines.append(f"  --fs-{kebab(key)}: {value};")
    for group in ("space", "radius", "control", "motion"):
        for key, value in tokens[group].items():
            lines.append(f"  --{group}-{kebab(key)}: {value};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = render(json.loads(SOURCE.read_text()))
    if "--check" in argv:
        if not TARGET.exists() or TARGET.read_text() != text:
            print(f"{TARGET.relative_to(ROOT)} is out of date; run python tools/build_tokens.py")
            return 1
        print("tokens.css: up to date")
        return 0
    TARGET.write_text(text)
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
