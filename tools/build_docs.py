"""Build and check the public docs site (DOC-01, DOC-04, SDK-03) and the website's code tabs (WEB-04).

    python tools/build_docs.py           # write docs/api/postman.json, the pages' code samples, the site's tabs
    python tools/build_docs.py --check   # fail if either is stale or the site is incomplete

Code samples are files under docs/snippets/<lang>/, run in CI by tools/run_snippets.py. A page shows one as a
<CodeGroup> between `{/* snippet: <name> */}` and `{/* /snippet */}`; this tool writes the group from the files'
`docs:start` ... `docs:end` regions, so a page never shows code that was not run.

The site is Mintlify, from `docs/` (`docs/docs.json`). `docs/` also holds internal documents (brand, design,
product, engineering standards), so the check makes sure every Markdown page is either in the navigation or
excluded by `docs/.mintignore`: nothing internal is published by accident.
"""

from __future__ import annotations

import json
import re
import sys
import textwrap
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
OPENAPI = DOCS / "api" / "openapi.json"
POSTMAN = DOCS / "api" / "postman.json"
SITE_SNIPPETS = ROOT / "apps" / "site" / "src" / "data" / "snippets.json"  # WEB-04: the site's code tabs
PAGE_SUFFIXES = (".mdx", ".md")
_METHODS = ("get", "post", "put", "patch", "delete")
SNIPPETS = DOCS / "snippets"
# (tab title, fence language, folder) in the order the tabs are shown
SNIPPET_LANGS = [("cURL", "bash", "curl"), ("Python", "python", "python"), ("TypeScript", "typescript", "typescript"),
                 ("Go", "go", "go"), ("Java", "java", "java"), ("C#", "csharp", "csharp"), ("PHP", "php", "php"),
                 ("Ruby", "ruby", "ruby")]  # fmt: skip
SNIPPET_FILES = {
    "verify_webhook": ["verify_webhook.sh", "verify_webhook.py", "verify_webhook.ts", "verify_webhook/verify.go",
                       "VerifyWebhook.java", "VerifyWebhook/Webhooks.cs", "verify_webhook.php", "verify_webhook.rb"],
    "create_payout": ["create_payout.sh", "create_payout.py", "create_payout.ts", "create_payout/main.go",
                      "CreatePayout.java", "CreatePayout/Program.cs", "create_payout.php", "create_payout.rb"],
}  # fmt: skip
_SNIPPET_BLOCK = re.compile(r"(\{/\* snippet: (\w+) \*/\}\n)(.*?)(\{/\* /snippet \*/\})", re.S)


def nav_pages(config: dict[str, Any]) -> list[str]:
    pages: list[str] = []

    def walk(node: Any) -> None:
        if isinstance(node, str):
            pages.append(node)
        elif isinstance(node, dict):
            for key in ("tabs", "groups", "pages"):
                for child in node.get(key, []):
                    walk(child)
        elif isinstance(node, list):
            for child in node:
                walk(child)

    walk(config["navigation"])
    return pages


def ignored() -> list[str]:
    lines = (DOCS / ".mintignore").read_text().splitlines()
    return [ln.strip() for ln in lines if ln.strip() and not ln.startswith("#")]


def _is_ignored(rel: str, patterns: list[str]) -> bool:
    return any(rel == p or (p.endswith("/") and rel.startswith(p)) for p in patterns)


def _page_file(page: str) -> Path | None:
    for suffix in PAGE_SUFFIXES:
        if (DOCS / f"{page}{suffix}").is_file():
            return DOCS / f"{page}{suffix}"
    return None


def snippet_region(path: Path) -> str:
    """The `docs:start` ... `docs:end` regions of a sample file, each dedented, joined by a blank line."""
    regions: list[list[str]] = []
    current: list[str] | None = None
    for line in path.read_text().splitlines():
        if "docs:start" in line:
            current = []
        elif "docs:end" in line:
            assert current is not None, f"{path}: docs:end without docs:start"
            regions.append(current)
            current = None
        elif current is not None:
            current.append(line)
    assert regions, f"{path}: needs docs:start ... docs:end"
    assert current is None, f"{path}: docs:start without docs:end"
    return "\n\n".join(textwrap.dedent("\n".join(r)).strip("\n") for r in regions)


def render_snippet(name: str) -> str:
    blocks = [f"```{fence} {title}\n{snippet_region(SNIPPETS / folder / file)}\n```"
              for (title, fence, folder), file in zip(SNIPPET_LANGS, SNIPPET_FILES[name], strict=True)]  # fmt: skip
    return "<CodeGroup>\n\n" + "\n\n".join(blocks) + "\n\n</CodeGroup>\n"


def _quickstart_block(info: str) -> str:
    page = (DOCS / "quickstart.mdx").read_text()
    m = re.search(rf"```{re.escape(info)}\n(.*?)```", page, re.S)
    assert m, f"docs/quickstart.mdx has no ```{info} block"
    return m.group(1).rstrip("\n")


def render_site_snippets() -> str:
    """The quickstart request for the website's code tabs (WEB-04): the same tested files as the docs."""
    data = {
        "_source": "Generated by tools/build_docs.py from docs/snippets and docs/quickstart.mdx. Do not edit.",
        "samples": [{"lang": title, "code": snippet_region(SNIPPETS / folder / file)}
                    for (title, _, folder), file in zip(SNIPPET_LANGS, SNIPPET_FILES["create_payout"], strict=True)],
        "payout": _quickstart_block("json payout.json"),
        "response": _quickstart_block("json"),
    }  # fmt: skip
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def render_page(source: str) -> str:
    """The page with every snippet group rewritten from its files."""
    return _SNIPPET_BLOCK.sub(lambda m: m.group(1) + render_snippet(m.group(2)) + m.group(4), source)


def mdx_issues(source: str) -> list[str]:
    """Characters that MDX reads as code outside code blocks and spans: a brace starts an expression and a
    lower-case `<` an HTML tag, and either breaks the page's build."""
    body = re.sub(r"\A---\n.*?\n---\n", "", source, flags=re.S)
    body = re.sub(r"```.*?```", "", body, flags=re.S)
    body = re.sub(r"`[^`\n]*`", "", body)
    body = re.sub(r"\{/\*.*?\*/\}", "", body, flags=re.S)  # MDX comments
    body = re.sub(
        r"<[A-Z][^>]*>|</[A-Z][A-Za-z]*>", "", body
    )  # components such as <Note> and <CardGroup cols={2}>
    return [f"MDX would read {m.group(0)!r} as code" for m in re.finditer(r"[{}]|<(?=[a-z!])", body)]


def build_postman(spec: dict[str, Any]) -> dict[str, Any]:
    """A Postman v2.1 collection: one request per operation, in folders by the operation's first tag."""
    folders: dict[str, list[dict[str, Any]]] = {}
    for path, item in spec["paths"].items():
        for method in _METHODS:
            op = item.get(method)
            if op is None:
                continue
            raw = "{{baseUrl}}" + path.replace("{", "{{").replace("}", "}}")
            headers = [
                {"key": "Authorization", "value": "Bearer {{apiKey}}"},
                {"key": "DekernAI-Version", "value": "{{apiVersion}}"},
            ]
            request: dict[str, Any] = {
                "method": method.upper(),
                "header": headers,
                "url": {"raw": raw, "host": ["{{baseUrl}}"], "path": [p for p in raw.split("/")[1:] if p]},
                "description": op.get("description", ""),
            }
            names = {p.get("name") for p in op.get("parameters", []) if p.get("in") == "header"}
            if method == "post" and "Idempotency-Key" in names:
                headers.append({"key": "Idempotency-Key", "value": "{{$guid}}"})
            if "requestBody" in op:
                headers.append({"key": "Content-Type", "value": "application/json"})
                request["body"] = {"mode": "raw", "raw": "{}", "options": {"raw": {"language": "json"}}}
            tag = (op.get("tags") or ["API"])[0]
            folders.setdefault(tag, []).append({"name": op.get("summary") or f"{method.upper()} {path}",
                                                "request": request})  # fmt: skip
    return {
        "info": {
            "name": spec["info"]["title"],
            "description": spec["info"].get("description", ""),
            "version": spec["info"]["version"],
            "schema": "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
        },
        "variable": [
            {"key": "baseUrl", "value": spec["servers"][0]["url"]},  # the hosted sandbox
            {"key": "apiKey", "value": "sk_test_..."},
            {"key": "apiVersion", "value": spec["info"]["version"]},
        ],
        "item": [{"name": name, "item": items} for name, items in folders.items()],
    }


def render_postman() -> str:
    return json.dumps(build_postman(json.loads(OPENAPI.read_text())), indent=2) + "\n"


def problems() -> list[str]:
    out: list[str] = []
    config = json.loads((DOCS / "docs.json").read_text())
    pages = nav_pages(config)
    patterns = ignored()
    for page in pages:
        if _page_file(page) is None:
            out.append(f"docs.json names a page that does not exist: {page}")
    for tab in config["navigation"].get("tabs", []):
        if "openapi" in tab and not (DOCS / tab["openapi"]).is_file():
            out.append(f"docs.json names an OpenAPI file that does not exist: {tab['openapi']}")
    for p in patterns:
        if not (DOCS / p.rstrip("/")).exists():
            out.append(f".mintignore names something that does not exist: {p}")
    listed = {str(_page_file(p).relative_to(DOCS)) for p in pages if _page_file(p) is not None}  # type: ignore[union-attr]
    for f in sorted(DOCS.rglob("*")):
        rel = f.relative_to(DOCS).as_posix()
        if f.suffix in PAGE_SUFFIXES and rel not in listed and not _is_ignored(rel, patterns):
            out.append(f"{rel} is neither in the navigation nor in .mintignore (it would be published)")
    for page in pages:
        f = _page_file(page)
        if f is not None:
            source = f.read_text()
            out += [f"{page}: {issue}" for issue in mdx_issues(source)]
            if render_page(source) != source:
                out.append(f"{page}: its code samples are stale: run python tools/build_docs.py")
    if not POSTMAN.is_file() or POSTMAN.read_text() != render_postman():
        out.append("docs/api/postman.json is stale: run python tools/build_docs.py")
    if not SITE_SNIPPETS.is_file() or SITE_SNIPPETS.read_text() != render_site_snippets():
        out.append("apps/site/src/data/snippets.json is stale: run python tools/build_docs.py")
    return out


def main(argv: list[str]) -> int:
    if "--check" in argv:
        found = problems()
        for p in found:
            print(f"docs: {p}")
        print("docs: OK" if not found else f"docs: {len(found)} problem(s)")
        return 1 if found else 0
    POSTMAN.write_text(render_postman())
    print(f"wrote {POSTMAN.relative_to(ROOT)}")
    SITE_SNIPPETS.write_text(render_site_snippets())
    print(f"wrote {SITE_SNIPPETS.relative_to(ROOT)}")
    for page in nav_pages(json.loads((DOCS / "docs.json").read_text())):
        f = _page_file(page)
        if f is not None and render_page(source := f.read_text()) != source:
            f.write_text(render_page(source))
            print(f"wrote the code samples in {f.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
