"""OPS-04: build docs/security.md, the security pack draft, from spec/10 and the test evidence.

    python tools/build_security.py           # write docs/security.md
    python tools/build_security.py --check   # fail if docs/security.md is out of date

Sources: the "Security controls in the MVP" table and the "Roadmap, not built" line in
spec/10-security-and-deploy.md, and the tests recorded per story in specs/001-detent-mvp/test-map.yaml.
Each control lists the stories that built it and their tests. Roadmap items are labelled as roadmap.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "spec" / "10-security-and-deploy.md"
TEST_MAP = ROOT / "specs" / "001-detent-mvp" / "test-map.yaml"
OUT = ROOT / "docs" / "security.md"
STORY = re.compile(r"\b[A-Z]{2,4}-\d{2}\b")


def controls(spec: str) -> tuple[list[tuple[str, str]], list[str]]:
    section = spec.split("## Security controls in the MVP", 1)[1].split("\n## ", 1)[0]
    rows = []
    for line in section.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 2 and cells[0] not in ("Control", "---") and not set(cells[0]) <= {"-"}:
            rows.append((cells[0], cells[1]))
    m = re.search(r"\*\*Roadmap, not built:\*\*\s*(.+?)\.", section)
    roadmap = [x.strip() for x in re.split(r",\s*", m.group(1))] if m else []
    return rows, roadmap


def tests_for(stories: list[str], test_map: dict[str, dict[int, list[str]]]) -> list[str]:
    out: list[str] = []
    for s in stories:
        for node_ids in (test_map.get(s) or {}).values():
            for t in node_ids:
                if t not in out:
                    out.append(t)
    return out


def build() -> str:
    rows, roadmap = controls(SPEC.read_text())
    test_map = yaml.safe_load(TEST_MAP.read_text()) or {}
    lines = [
        "# Security pack (draft)",
        "",
        "<!-- Generated by tools/build_security.py from spec/10-security-and-deploy.md and",
        "     specs/001-detent-mvp/test-map.yaml. Edit those, then run the tool. -->",
        "",
        "DekernAI is agentic payment controls: it decides, orchestrates and operates deposits and payouts beside a",
        "platform's own rails. It never holds client funds or keys in production; the prototype holds test-network",
        "keys only. This draft lists the controls as built and the tests that check them, to seed a pen test and",
        "vendor due diligence later. It is not a certification.",
        "",
        "## Controls as built",
        "",
    ]
    for control, where in rows:
        stories = STORY.findall(where)
        tests = tests_for(stories, test_map)
        lines.append(f"### {control}")
        lines.append("")
        lines.append(f"Where: {where}.")
        lines.append("")
        if tests:
            lines.append("Tests:")
            lines.append("")
            lines += [f"- `{t}`" for t in tests]
        else:
            lines.append("Tests: none recorded yet (a gap to close before a pen test).")
        lines.append("")
    lines += ["## Roadmap (not built)", ""]
    lines += [f"- Roadmap: {r}" for r in roadmap] or ["- None listed."]
    lines += [
        "",
        "## Limits of this draft",
        "",
        "- Prototype: test networks and the simulated bank only; the screening list is a mock.",
        "- Tests are listed from the recorded evidence per story; `ci:` and `manual:` entries are checks outside pytest.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("docs/security.md is out of date: run python tools/build_security.py", file=sys.stderr)
            return 1
        print("security: OK")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
