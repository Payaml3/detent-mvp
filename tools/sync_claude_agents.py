"""Build Claude Code agents (.claude/agents/*.md) from the role definitions in .codex/agents/*.toml.

The solo-to-scale plugin generates the Codex agents. This mirrors them for Claude Code, so the same team
works when the plugin is not installed. Edit the role in the plugin, re-sync the Codex agents, then run
`python tools/sync_claude_agents.py`. `--check` fails when the Claude agents are out of date.
"""

from __future__ import annotations

import argparse
import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / ".codex" / "agents"
DST = ROOT / ".claude" / "agents"

# Codex model tiers to Claude Code aliases (AGENTS.md "Model choice").
MODEL = {"gpt-6.2-astra": "opus", "gpt-6.2-sol": "sonnet"}
# Roles whose model depends on the work: money, security and data-integrity paths need the strongest
# model, so they run on the model the session was started with.
INHERIT = {"engineer"}
READ_ONLY_TOOLS = "Read, Grep, Glob, WebSearch, WebFetch"


def render(role: dict) -> str:
    name = role["name"]
    model = "inherit" if name in INHERIT else MODEL.get(role.get("model", ""), "inherit")
    lines = [
        "---",
        f"name: {name}",
        f"description: {json.dumps(role['description'], ensure_ascii=False)}",
        f"model: {model}",
    ]
    if role.get("sandbox_mode") == "read-only":
        lines.append(f"tools: {READ_ONLY_TOOLS}")
    lines += [
        "---",
        f"<!-- Generated by tools/sync_claude_agents.py from .codex/agents/{name}.toml. Do not edit. -->",
        "",
        role["developer_instructions"].strip(),
        "",
    ]
    return "\n".join(lines)


def build() -> dict[Path, str]:
    out = {}
    for path in sorted(SRC.glob("*.toml")):
        role = tomllib.loads(path.read_text(encoding="utf-8"))
        out[DST / f"{role['name']}.md"] = render(role)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if .claude/agents is out of date")
    args = ap.parse_args()
    wanted = build()
    if not wanted:
        print(f"no roles found in {SRC}", file=sys.stderr)
        return 1
    existing = {p for p in DST.glob("*.md")} if DST.exists() else set()
    stale = [p for p, text in wanted.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    extra = sorted(existing - set(wanted))
    if args.check:
        for p in stale + extra:
            print(f"out of date: {p.relative_to(ROOT)}", file=sys.stderr)
        if stale or extra:
            print("run: python tools/sync_claude_agents.py", file=sys.stderr)
            return 1
        print(f"{len(wanted)} Claude agents match .codex/agents")
        return 0
    DST.mkdir(parents=True, exist_ok=True)
    for p in stale:
        p.write_text(wanted[p], encoding="utf-8")
    for p in extra:
        p.unlink()
    print(f"wrote {len(stale)}, removed {len(extra)}, {len(wanted)} agents in {DST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
