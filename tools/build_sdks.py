"""Generate the SDKs' models and resources from the OpenAPI file (SDK-01, SDK-02).

    python tools/build_sdks.py           # write the generated files
    python tools/build_sdks.py --check   # fail if they are stale

The generated part of each SDK is its typed models and one method per API operation, named in `NAMES`. The
hand-written part (the client: keys, idempotency, retries, errors, webhook verification) lives beside it:
`sdks/python/src/dekernai/_client.py` and `sdks/typescript/src/client.ts`. A new operation without a name
here fails the build, so the SDKs can't silently miss an endpoint.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
OPENAPI = ROOT / "docs" / "api" / "openapi.json"
PY_OUT = ROOT / "sdks" / "python" / "src" / "dekernai" / "_generated.py"
TS_OUT = ROOT / "sdks" / "typescript" / "src" / "generated.ts"
HEADER = "Generated by tools/build_sdks.py from docs/api/openapi.json. Do not edit."
_METHODS = ("get", "post", "put", "patch", "delete")

# operationId -> (resource, method). Python uses these names; TypeScript uses their camelCase form.
NAMES: dict[str, tuple[str, str]] = {
    "postPaymentIntents": ("payment_intents", "create"),
    "getPaymentIntents": ("payment_intents", "list"),
    "getPaymentIntentsPaymentId": ("payment_intents", "retrieve"),
    "postPaymentIntentsPaymentIdSend": ("payment_intents", "send"),
    "postPaymentIntentsPaymentIdCancel": ("payment_intents", "cancel"),
    "getPaymentIntentsPaymentIdReplay": ("payment_intents", "replay"),
    "postDecisions": ("decisions", "create"),
    "getExceptions": ("exceptions", "list"),
    "getExceptionsCaseId": ("exceptions", "retrieve"),
    "postExceptionsCaseIdApprove": ("exceptions", "approve"),
    "postExceptionsCaseIdReject": ("exceptions", "reject"),
    "postKillSwitch": ("kill_switch", "engage"),
    "deleteKillSwitch": ("kill_switch", "release"),
    "getRequestLogs": ("request_logs", "list"),
    "getMandates": ("mandates", "list"),
    "postMandatesMandateIdRevoke": ("mandates", "revoke"),
    "getPolicyVersions": ("policy", "list_versions"),
    "getPolicyVersionsVersion": ("policy", "retrieve_version"),
    "postDepositIntents": ("deposit_intents", "create"),
    "getDepositIntentsDepositId": ("deposit_intents", "retrieve"),
    "getReconciliationRuns": ("reconciliation", "list_runs"),
    "getReconciliationBreaks": ("reconciliation", "list_breaks"),
    "postWebhookEndpoints": ("webhook_endpoints", "create"),
    "getWebhookEndpoints": ("webhook_endpoints", "list"),
    "getWebhookEndpointsEndpointId": ("webhook_endpoints", "retrieve"),
    "deleteWebhookEndpointsEndpointId": ("webhook_endpoints", "delete"),
    "postWebhookEndpointsEndpointIdTest": ("webhook_endpoints", "test"),
    "getWebhookEndpointsEndpointIdDeliveries": ("webhook_endpoints", "list_deliveries"),
    "postWebhookEndpointsEndpointIdResend": ("webhook_endpoints", "resend"),
    "getEvents": ("events", "list"),
    "getEventsEventId": ("events", "retrieve"),
}


def camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(p.title() for p in rest)


def pascal(name: str) -> str:
    return "".join(p.title() for p in name.split("_"))


def py_ident(name: str) -> str:
    return re.sub(r"\W+", "_", name).strip("_")


# ------------------------------------------------------------------------------------------------ types
def _ref(schema: dict[str, Any]) -> str | None:
    ref = schema.get("$ref")
    return ref.rsplit("/", 1)[1] if isinstance(ref, str) else None


def _page_item(schema: dict[str, Any]) -> dict[str, Any] | None:
    props = schema.get("properties", {})
    if schema.get("type") == "object" and {"data", "has_more", "next_cursor"} <= set(props):
        items: dict[str, Any] = props["data"].get("items", {})
        return items
    return None


def _union(types: list[str], sep: str) -> str:
    parts = [p for t in types for p in t.split(sep)]
    return sep.join(dict.fromkeys(parts))


def py_type(schema: dict[str, Any]) -> str:
    return _union([_py_type(schema)], " | ")


def ts_type(schema: dict[str, Any]) -> str:
    return _union([_ts_type(schema)], " | ")


def _py_type(schema: dict[str, Any]) -> str:
    if (name := _ref(schema)) is not None:
        return name
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(dict.fromkeys(py_type(s) for s in schema[key]))
    if "const" in schema:
        return f"Literal[{json.dumps(schema['const'])}]"
    if "enum" in schema:
        values = [v for v in schema["enum"] if v is not None]
        lit = "Literal[" + ", ".join(json.dumps(v) for v in values) + "]"
        return lit + (" | None" if None in schema["enum"] else "")
    t = schema.get("type")
    if isinstance(t, list):
        return " | ".join(py_type({**schema, "type": x}) for x in t)
    if (item := _page_item(schema)) is not None:
        return f"Page[{py_type(item)}]"
    if t == "array":
        return f"list[{py_type(schema.get('items', {}))}]"
    scalars = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "null": "None"}
    return scalars.get(str(t), "dict[str, Any]")


def _ts_type(schema: dict[str, Any]) -> str:
    if (name := _ref(schema)) is not None:
        return name
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(dict.fromkeys(ts_type(s) for s in schema[key]))
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    t = schema.get("type")
    if isinstance(t, list):
        return " | ".join(ts_type({**schema, "type": x}) for x in t)
    if (item := _page_item(schema)) is not None:
        return f"Page<{ts_type(item)}>"
    if t == "array":
        inner = ts_type(schema.get("items", {}))
        return f"Array<{inner}>"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(str(t), "Record<string, unknown>")


def _doc(schema: dict[str, Any]) -> str:
    return " ".join(str(schema.get("description", "")).split())


# ------------------------------------------------------------------------------------------- operations
def operations(spec: dict[str, Any]) -> list[dict[str, Any]]:
    ops = []
    for path, item in spec["paths"].items():
        for method in _METHODS:
            op = item.get(method)
            if op is None:
                continue
            oid = op["operationId"]
            if oid not in NAMES:
                raise SystemExit(f"build_sdks: name the operation {oid} ({method.upper()} {path}) in NAMES")
            params = op.get("parameters", [])
            body = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            ok = next((r for c, r in sorted(op["responses"].items()) if c.startswith("2")), {})
            ret = ok.get("content", {}).get("application/json", {}).get("schema", {})
            resource, name = NAMES[oid]
            ops.append(
                {
                    "resource": resource,
                    "name": name,
                    "method": method.upper(),
                    "path": path,
                    "summary": op.get("summary") or f"{method.upper()} {path}",
                    "path_params": [p for p in params if p.get("in") == "path"],
                    "query": [p for p in params if p.get("in") == "query"],
                    "idempotent": any(
                        p.get("name") == "Idempotency-Key" for p in params if p.get("in") == "header"
                    ),
                    "body": body,
                    "body_required": bool(op.get("requestBody", {}).get("required")),
                    "returns": ret,
                }
            )
    unused = set(NAMES) - {o for item in spec["paths"].values() for m, o in _op_ids(item)}
    if unused:
        raise SystemExit(f"build_sdks: NAMES has operations the API no longer has: {sorted(unused)}")
    return ops


def _op_ids(item: dict[str, Any]) -> list[tuple[str, str]]:
    return [(m, item[m]["operationId"]) for m in _METHODS if m in item]


def _resources(ops: list[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    out: dict[str, list[dict[str, Any]]] = {}
    for op in ops:
        out.setdefault(op["resource"], []).append(op)
    return out


# -------------------------------------------------------------------------------------------------- Python
def render_python(spec: dict[str, Any]) -> str:
    schemas = spec["components"]["schemas"]
    out = [
        f'"""{HEADER}"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any, Generic, Literal, NotRequired, Protocol, TypedDict, TypeVar, cast",
        "from urllib.parse import quote",
        "",
        f"API_VERSION = {json.dumps(spec['info']['version'])}",
        "",
        'T = TypeVar("T")',
        "",
        "",
        "class Page(TypedDict, Generic[T]):",
        '    """One page of a list. Pass `next_cursor` as `starting_after` for the next page."""',
        "",
        "    data: list[T]",
        "    has_more: bool",
        "    next_cursor: str | None",
        "",
    ]
    for name, schema in schemas.items():
        out += ["", ""]
        if schema.get("type") != "object" and "properties" not in schema:
            out.append(f"{name} = {py_type({k: v for k, v in schema.items() if k != 'title'})}")
            continue
        out.append(f"class {name}(TypedDict):")
        doc = _doc(schema)
        if doc:
            out += [f'    """{doc}"""', ""]
        required = set(schema.get("required", []))
        props = schema.get("properties", {})
        if not props and not doc:
            out.append("    pass")
        for field, fs in props.items():
            t = py_type(fs)
            out.append(f"    {field}: {t if field in required else f'NotRequired[{t}]'}")
    out += [
        "",
        "",
        "class Requester(Protocol):",
        "    def _request(",
        "        self,",
        "        method: str,",
        "        path: str,",
        "        *,",
        "        body: Any = None,",
        "        query: dict[str, Any] | None = None,",
        "        idempotent: bool = False,",
        "        idempotency_key: str | None = None,",
        "    ) -> Any: ...",
        "",
        "",
        "class _Resource:",
        "    def __init__(self, client: Requester) -> None:",
        "        self._client = client",
    ]
    resources = _resources(operations(spec))
    for resource, ops in resources.items():
        out += ["", "", f"class {pascal(resource)}(_Resource):"]
        for op in ops:
            out += ["", *_py_method(op)]
    out += ["", "", "class Resources:", '    """The API, one attribute per resource."""', ""]
    out += [f"    {r}: {pascal(r)}" for r in resources]
    out += ["", "    def _init_resources(self, client: Requester) -> None:"]
    out += [f"        self.{r} = {pascal(r)}(client)" for r in resources]
    return "\n".join(out) + "\n"


def _py_method(op: dict[str, Any]) -> list[str]:
    args = ["self"] + [f"{p['name']}: {py_type(p.get('schema', {}))}" for p in op["path_params"]]
    if op["body"] is not None:
        args.append(f"params: {py_type(op['body'])}")
    kw = [
        f"{py_ident(q['name'])}: {py_type({'anyOf': [q.get('schema', {}), {'type': 'null'}]})} = None"
        for q in op["query"]
    ]
    if op["idempotent"]:
        kw.append("idempotency_key: str | None = None")
    if kw:
        args += ["*", *kw]
    ret = py_type(op["returns"]) if op["returns"] else "dict[str, Any]"
    path = op["path"]
    for p in op["path_params"]:
        path = path.replace("{" + p["name"] + "}", "{quote(str(" + p["name"] + "), safe='')}")
    call = [f'"{op["method"]}"', f'f"{path}"' if op["path_params"] else f'"{path}"']
    if op["body"] is not None:
        call.append("body=params")
    if op["query"]:
        q = ", ".join(f'"{x["name"]}": {py_ident(x["name"])}' for x in op["query"])
        call.append(f"query={{{q}}}")
    if op["idempotent"]:
        call += ["idempotent=True", "idempotency_key=idempotency_key"]
    sig = f"    def {op['name']}({', '.join(args)}) -> {ret}:"
    lines = (
        [sig]
        if len(sig) <= 110
        else [f"    def {op['name']}(", *[f"        {a}," for a in args], f"    ) -> {ret}:"]
    )
    lines.append(f'        """{op["summary"]} (`{op["method"]} {op["path"]}`)."""')
    lines.append(f'        return cast("{ret}", self._client._request({", ".join(call)}))')
    return lines


# ---------------------------------------------------------------------------------------------- TypeScript
def render_typescript(spec: dict[str, Any]) -> str:
    schemas = spec["components"]["schemas"]
    out = [
        f"// {HEADER}",
        "",
        'import type { RequestOptions } from "./client.js";',
        "",
        f"export const API_VERSION = {json.dumps(spec['info']['version'])};",
        "",
        "/** One page of a list. Pass `next_cursor` as `starting_after` for the next page. */",
        "export interface Page<T> {",
        "  data: Array<T>;",
        "  has_more: boolean;",
        "  next_cursor: string | null;",
        "}",
    ]
    for name, schema in schemas.items():
        out.append("")
        if doc := _doc(schema):
            out.append(f"/** {doc} */")
        if schema.get("type") != "object" and "properties" not in schema:
            out.append(f"export type {name} = {ts_type({k: v for k, v in schema.items() if k != 'title'})};")
            continue
        required = set(schema.get("required", []))
        out.append(f"export interface {name} {{")
        for field, fs in schema.get("properties", {}).items():
            out.append(f"  {field}{'' if field in required else '?'}: {ts_type(fs)};")
        out.append("}")
    out += [
        "",
        "export interface Requester {",
        "  request<T>(options: RequestOptions): Promise<T>;",
        "}",
    ]
    resources = _resources(operations(spec))
    for resource, ops in resources.items():
        out += [
            "",
            f"export class {pascal(resource)} {{",
            "  constructor(private readonly client: Requester) {}",
        ]
        for op in ops:
            out += ["", *_ts_method(op)]
        out.append("}")
    out += ["", "export function resources(client: Requester) {", "  return {"]
    out += [f"    {camel(r)}: new {pascal(r)}(client)," for r in resources]
    out += ["  };", "}"]
    return "\n".join(out) + "\n"


def _ts_method(op: dict[str, Any]) -> list[str]:
    args = [f"{camel(p['name'])}: {ts_type(p.get('schema', {}))}" for p in op["path_params"]]
    if op["body"] is not None:
        args.append(f"params: {ts_type(op['body'])}")
    opts = [f'"{q["name"]}"?: {ts_type(q.get("schema", {}))}' for q in op["query"]]
    if op["idempotent"]:
        opts.append("idempotencyKey?: string")
    if opts:
        args.append(f"options: {{ {'; '.join(opts)} }} = {{}}")
    ret = ts_type(op["returns"]) if op["returns"] else "Record<string, unknown>"
    path = op["path"]
    for p in op["path_params"]:
        path = path.replace("{" + p["name"] + "}", "${encodeURIComponent(String(" + camel(p["name"]) + "))}")
    fields = [f'method: "{op["method"]}"', f"path: `{path}`"]
    if op["body"] is not None:
        fields.append("body: params")
    if op["query"]:
        q = ", ".join(f'"{x["name"]}": options["{x["name"]}"]' for x in op["query"])
        fields.append(f"query: {{ {q} }}")
    if op["idempotent"]:
        fields += ["idempotent: true", "idempotencyKey: options.idempotencyKey"]
    return [
        f"  /** {op['summary']} (`{op['method']} {op['path']}`). */",
        f"  {camel(op['name'])}({', '.join(args)}): Promise<{ret}> {{",
        f"    return this.client.request<{ret}>({{ {', '.join(fields)} }});",
        "  }",
    ]


# ------------------------------------------------------------------------------------------------- main
def _ruff_format(source: str, path: Path) -> str:
    """The repository's own formatter, so the generated file passes `ruff format --check` as written."""
    cmd = [sys.executable, "-m", "ruff", "format", "--stdin-filename", str(path), "-"]
    done = subprocess.run(cmd, input=source, capture_output=True, text=True, check=True, cwd=ROOT)
    return done.stdout


def rendered() -> dict[Path, str]:
    spec = json.loads(OPENAPI.read_text())
    return {PY_OUT: _ruff_format(render_python(spec), PY_OUT), TS_OUT: render_typescript(spec)}


def main(argv: list[str]) -> int:
    files = rendered()
    if "--check" in argv:
        stale = [p for p, text in files.items() if not p.is_file() or p.read_text() != text]
        for p in stale:
            print(f"sdks: {p.relative_to(ROOT)} is stale: run python tools/build_sdks.py")
        print("sdks: OK" if not stale else f"sdks: {len(stale)} stale file(s)")
        return 1 if stale else 0
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
