def body(no: str, issue: str, due: str | None, lines: list[tuple[str, int, str, str]], total: str) -> str:
    out = [f"INVOICE  Invoice no: {no}   Issue date: {issue}" + (f"   Due date: {due}" if due else "")]
    for desc, qty, unit, amount in lines:
        out.append(f"{desc:<44}{qty:>4}    USD {unit:>9}   USD {amount}")
    out.append(f"{'':<54}Total:    USD {total}")
    return "\n".join(out)


def f(value: str | None, conf: float = 0.97) -> dict[str, object]:
    return {"value": value, "confidence": conf if value is not None else 0.0, "source_span": None}


def answer(
    payee: str | None,
    cpt: str | None,
    amount: str | None,
    currency: str | None,
    network: str | None,
    wallet: str | None,
    no: str | None,
    due: str | None,
    flags: list[str] | None = None,
) -> dict[str, object]:
    return {
        "proposal": {
            "payee_name": f(payee),
            "counterparty_id": f(cpt, 0.9),
            "amount": f(amount),
            "currency": f(currency),
            "network": f(network),
            "wallet_address": f(wallet),
            "invoice_number": f(no),
            "due_date": f(due),
        },
        "flags": [{"code": c, "detail": "reported by the model", "fields": []} for c in (flags or [])],
        "requires_clarification": bool(flags),
    }


CASES: list[dict[str, object]] = []


def case(
    name: str,
    kind: str,
    text: str,
    ans: dict[str, object],
    fields: dict[str, object],
    flags: list[str],
    note: str = "",
) -> None:
    CASES.append(
        {
            "name": name,
            "kind": kind,
            "text": text,
            "answer": ans,
            "fields": fields,
            "flags": flags,
            "note": note,
        }
    )


