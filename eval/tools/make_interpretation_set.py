def main() -> None:
    assert len(CASES) == 24, len(CASES)
    expected = {}
    for c in CASES:
        name = str(c["name"])
        (INV / name).write_text(str(c["text"]))
        no = next(str(v["value"]) for k, v in c["answer"]["proposal"].items() if k == "invoice_number")  # type: ignore[index]
        rec = {
            "_provenance": PROVENANCE.format(note=c["note"]).strip(),
            "match": no,
            "usage": {"input_tokens": 1500, "output_tokens": 380},
            "output": c["answer"],
        }
        (REC / f"set-{no.lower()}.json").write_text(json.dumps(rec, indent=2) + "\n")
        expected[name] = {"kind": c["kind"], "fields": c["fields"], "flags": c["flags"]}
    (INV / "interpretation-set.yaml").write_text(
        "# EVL-04 interpretation set: the 24 invoices added in S8 (the first six are in expected-outputs.yaml).\n"
        "# Generated by eval/tools/make_interpretation_set.py. null = must be null (and flagged).\n"
        + yaml.safe_dump(expected, sort_keys=False, width=120)
    )


if __name__ == "__main__":
    main()
