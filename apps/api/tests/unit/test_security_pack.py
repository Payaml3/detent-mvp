"""OPS-04: docs/security.md is generated from spec/10, lists each control with its tests, labels the roadmap."""

from __future__ import annotations

import subprocess
import sys

from detent.settings import REPO_ROOT

TOOL = REPO_ROOT / "tools" / "build_security.py"


def test_security_pack_is_current() -> None:
    r = subprocess.run([sys.executable, str(TOOL), "--check"], capture_output=True, text=True)
    assert r.returncode == 0, r.stderr


def test_controls_have_tests_and_roadmap_is_labelled() -> None:
    doc = (REPO_ROOT / "docs" / "security.md").read_text()
    spec = (REPO_ROOT / "spec" / "10-security-and-deploy.md").read_text()
    assert "Generated by tools/build_security.py" in doc
    assert "### Rail credentials encrypted at rest (Fernet), never displayed again" in doc
    assert "`integration/test_rail_connect.py::test_api_key_is_encrypted_never_shown_and_audited`" in doc
    assert "### Test networks only; live keys rejected" in doc and "test_live_keys_are_always_rejected" in doc
    for item in ("hardware-backed vault", "IP allowlists", "pen test", "SOC 2"):
        assert item in spec and f"- Roadmap: {item}" in doc
    assert "certified" not in doc.lower().replace("not a certification", "")
